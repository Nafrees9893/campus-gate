PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','user'))
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS visitors (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT NOT NULL DEFAULT '',
 phone TEXT NOT NULL DEFAULT '', organization TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS hosts (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE,
 department TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS visits (
 id INTEGER PRIMARY KEY AUTOINCREMENT, visitor_id INTEGER NOT NULL REFERENCES visitors(id) ON DELETE RESTRICT,
 host_id INTEGER NOT NULL REFERENCES hosts(id) ON DELETE RESTRICT,
 purpose TEXT NOT NULL, check_in TEXT NOT NULL, check_out TEXT,
 CHECK(check_out IS NULL OR check_out>=check_in)
);
CREATE UNIQUE INDEX IF NOT EXISTS single_open_visit ON visits(visitor_id) WHERE check_out IS NULL;
CREATE INDEX IF NOT EXISTS visits_arrival ON visits(check_in);
CREATE INDEX IF NOT EXISTS visits_host ON visits(host_id);
